/**
 * Generate skills/monkey-mini-app/references/theme.md from the locked token list
 * plus one builtin theme file for sample values.
 *
 * Inputs: packages/host/src/theme/tokens.ts, packages/host/themes/theme-slate.css
 * Writes: skills/monkey-mini-app/references/theme.md
 * Side effects: repo tracked files
 * Run as: pnpm gen:skill
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..")
const tokensPath = path.join(root, "packages/host/src/theme/tokens.ts")
const sampleThemePath = path.join(root, "packages/host/themes/theme-slate.css")
const outPath = path.join(root, "skills/monkey-mini-app/references/theme.md")

const CLASS_HINT = {
  background: "bg-background",
  foreground: "text-foreground",
  card: "bg-card",
  "card-foreground": "text-card-foreground",
  border: "border-border",
  muted: "bg-muted",
  "muted-foreground": "text-muted-foreground",
  primary: "bg-primary · text-primary",
  "primary-foreground": "text-primary-foreground",
  secondary: "bg-secondary",
  "secondary-foreground": "text-secondary-foreground",
  accent: "bg-accent",
  "accent-foreground": "text-accent-foreground",
  destructive: "bg-destructive",
  "destructive-foreground": "text-destructive-foreground",
  ring: "ring-ring",
  input: "border-input",
  radius: "rounded-*",
  shadow: "shadow-*",
}

const CATEGORIES = [
  ["Surface", /^(background|card)$/],
  ["Text", /foreground$/],
  ["Brand & status", /^(primary|secondary|accent|muted|destructive)$/],
  ["Lines & focus", /^(border|ring|input)$/],
  ["Radius & shadow", /^(radius|shadow)$/],
]

function readTokenNames() {
  const src = fs.readFileSync(tokensPath, "utf8")
  const names = [...src.matchAll(/^\s+'([a-z0-9-]+)',$/gm)].map((m) => m[1])
  if (names.length < 8) throw new Error(`[gen-theme] too few tokens in ${tokensPath}`)
  const required = [...src.matchAll(/requiredThemeTokens = \[([^\]]+)\]/gs)]
  const requiredNames = required.length
    ? [...required[0][1].matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1])
    : ["background", "foreground", "primary"]
  return { names, requiredNames }
}

function readBlock(src, selector) {
  const at = src.indexOf(selector)
  if (at < 0) return {}
  const open = src.indexOf("{", at)
  if (open < 0) return {}
  let depth = 0
  let close = -1
  for (let i = open; i < src.length; i++) {
    if (src[i] === "{") depth++
    else if (src[i] === "}") {
      depth--
      if (depth === 0) {
        close = i
        break
      }
    }
  }
  if (close < 0) return {}
  const vars = {}
  for (const m of src.slice(open + 1, close).matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    vars[m[1]] = m[2].trim()
  }
  return vars
}

function shorten(value, max = 34) {
  const v = value.replace(/\s+/g, " ")
  return v.length > max ? `${v.slice(0, max - 1)}…` : v
}

function categoryOf(name) {
  for (const [label, re] of CATEGORIES) if (re.test(name)) return label
  return "Other"
}

export function generateThemeDoc() {
  const { names, requiredNames } = readTokenNames()
  const css = fs.readFileSync(sampleThemePath, "utf8")
  const light = readBlock(css, ':root[data-mode="light"]')
  const dark = readBlock(css, ':root[data-mode="dark"]')
  const required = new Set(requiredNames)

  const byCategory = new Map()
  for (const name of names) {
    const cat = categoryOf(name)
    if (!byCategory.has(cat)) byCategory.set(cat, [])
    byCategory.get(cat).push(name)
  }

  const lines = [
    "<!-- generated by scripts/gen/skill — do not edit -->",
    "",
    "# Theme tokens",
    "",
    "Colour comes from these names. Do not invent a second class for a token. Do not put hex in `ui.tsx`.",
    "The host sets `data-mode`. Do not set it.",
    "",
    "```tsx",
    '<div className="bg-card text-card-foreground border-border">',
    '  <span className="text-muted-foreground">…</span>',
    '  <button className="bg-primary text-primary-foreground">…</button>',
    "</div>",
    "```",
    "",
    "Use `var(--token)` only where a utility cannot reach: SVG fill, `color-mix()`, chart colour, or `style`.",
    "Token translucency: `color-mix(in oklch, var(--card) 60%, transparent)`, not `bg-card/60`.",
    "",
    "## Tokens",
    "",
  ]

  const order = [...CATEGORIES.map(([label]) => label), "Other"]
  for (const cat of order) {
    const list = byCategory.get(cat)
    if (!list?.length) continue
    lines.push(`### ${cat}`, "", "| Token | Tailwind | Light (slate) | Dark (slate) | Required |", "|---|---|---|---|---|")
    for (const name of list) {
      const cls = CLASS_HINT[name] ?? (name.endsWith("-foreground") ? `text-${name}` : `bg-${name}`)
      lines.push(
        `| \`--${name}\` | \`${cls}\` | \`${shorten(light[`--${name}`] ?? "—")}\` | \`${shorten(dark[`--${name}`] ?? "—")}\` | ${required.has(name) ? "yes" : "no"} |`,
      )
    }
    lines.push("")
  }

  lines.push(
    "## Custom host theme file",
    "",
    "Write this only when the user asks for a named palette. Path: `~/.mini-app/themes/theme-<id>.css`.",
    "`id` is `[a-z0-9-]+`. The same token names as the table. Both modes. Missing `background`, `foreground`, or `primary` in either mode ignores the whole file.",
    "This file is outside the app directory, so `mini_app_*` cannot write it. There is no second host-theme tool.",
    "",
    "```css",
    "/* name: Display name */",
    ':root[data-mode="light"] { --background: ; --foreground: ; --primary: ; }',
    ':root[data-mode="dark"] { --background: ; --foreground: ; --primary: ; }',
    "```",
    "",
    "## App-local palette (`theme.css`)",
    "",
    "Write `theme.css` in the app directory only when the look depends on a hue. Same token names, both modes, `/* name: … */` header.",
    "A plain CRUD or settings app does not ship this file. The user can still pick a host palette for that app.",
    "",
  )

  fs.writeFileSync(outPath, lines.join("\n"))
  return names.length
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`theme.md → ${generateThemeDoc()} tokens`)
}
